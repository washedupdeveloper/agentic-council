"""`claims.toml` is the source of both `verify` and `docs/CLAIMS.md`: one
sentence, one command that would falsify it."""

from __future__ import annotations

import argparse
import os
import re
import shlex
import subprocess
import sys
import tempfile
import tomllib
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
from pathlib import Path

DEFAULT_REGISTRY = Path("claims.toml")
DEFAULT_TIMEOUT = 900


@dataclass(frozen=True, slots=True)
class Claim:
    """One sentence this project asserts, and the command that proves it.

    `falsifier` names the mutation that must break this claim; the mutation run
    checks both directions, so a check that cannot fail is visible.
    """

    id: str
    text: str
    check: str
    falsifier: str | None = None


@dataclass(frozen=True, slots=True)
class ClaimResult:
    claim: Claim
    ok: bool
    detail: str


class RegistryError(ValueError):
    """The registry itself is malformed; nothing should run."""


def load(path: Path) -> list[Claim]:
    """Read and validate the registry. Every problem is reported at once."""
    try:
        raw = tomllib.loads(path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise RegistryError(f"cannot read {path}: {exc}") from exc
    except tomllib.TOMLDecodeError as exc:
        raise RegistryError(f"{path} is not valid TOML: {exc}") from exc

    entries = raw.get("claim")
    if not isinstance(entries, list) or not entries:
        raise RegistryError(f"{path} declares no [[claim]] entries")

    claims: list[Claim] = []
    problems: list[str] = []
    seen: set[str] = set()
    for index, entry in enumerate(entries, start=1):
        if not isinstance(entry, dict):
            problems.append(f"claim #{index} is not a table")
            continue
        ident = entry.get("id")
        text = entry.get("text")
        check = entry.get("check")
        falsifier = entry.get("falsifier")
        missing = [k for k, v in (("id", ident), ("text", text), ("check", check))
                   if not isinstance(v, str) or not v.strip()]
        if missing:
            problems.append(f"claim #{index} is missing {', '.join(missing)}")
            continue
        if falsifier is not None and (not isinstance(falsifier, str) or not falsifier.strip()):
            problems.append(f"claim #{index}: falsifier must be a non-empty string")
            continue
        assert isinstance(ident, str) and isinstance(text, str) and isinstance(check, str)
        if ident in seen:
            problems.append(f"duplicate claim id {ident!r}")
            continue
        seen.add(ident)
        if not text.rstrip().endswith("."):
            problems.append(f"{ident}: the text is a sentence, end it with a period")
        claims.append(Claim(ident, text, check, falsifier))

    if problems:
        raise RegistryError(f"{path}:\n  - " + "\n  - ".join(problems))
    return claims


HEADER = """# Claims

<!-- generated by `council-verify --write docs/CLAIMS.md`; do not edit -->

Every claim this project makes, and the command that would falsify it.
`council-verify` runs them all, and this page is generated from the same
registry, so it cannot describe a claim that has no check.

| id | claim | check |
|---|---|---|
"""


def render(claims: list[Claim]) -> str:
    """The registry as markdown. The only source of this table."""
    rows = [f"| `{c.id}` | {c.text} | `{c.check}` |" for c in claims]
    return HEADER + "\n".join(rows) + "\n"


def _is_pytest(argv: list[str]) -> bool:
    """True when the command is a pytest invocation, however it is spelled."""
    if argv and Path(argv[0]).name.startswith("pytest"):
        return True
    return any(token == "-m" and following == "pytest"
               for token, following in zip(argv, argv[1:]))


def _with_basetemp(argv: list[str], tmp: Path) -> list[str]:
    """Point pytest at its own basetemp, so it never builds numbered directories.

    `TempPathFactory.getbasetemp` only runs `make_numbered_dir_with_cleanup` when no
    basetemp is given, and that cleanup is where pytest leaves a scandir handle for
    the collector to warn about. Nothing about the check changes.
    """
    if not _is_pytest(argv):
        return argv
    # `-rs` puts the reason in the summary: a skip that counts as a pass is the one
    # result the claim registry must not accept, so the reason has to be legible.
    return [*argv, "-rs", f"--basetemp={tmp / 'pytest'}"]


SKIP_SUMMARY = re.compile(r"\b(\d+) skipped\b")


def _unproven(argv: list[str], stdout: str) -> str | None:
    """A reason when a pytest check proved nothing, or None when it proved its claim.

    pytest exits 0 when the selected node is skipped. The command "passed" without
    running, so a skip would count as a holding claim while nothing was falsified and
    nothing was checked -- the registry's premise (one sentence, one command that would
    falsify it) is only true if the command actually ran. Only node-level checks are
    judged this way: a file-level command that also collects an unrelated skipping test
    is not evidence about the claim.
    """
    if not _is_pytest(argv) or not any("::" in arg for arg in argv):
        return None
    match = SKIP_SUMMARY.search(stdout)
    if match is None or int(match.group(1)) == 0:
        return None
    reason = next(
        (line.strip() for line in stdout.splitlines() if line.strip().startswith("SKIPPED")),
        "the selected test skipped",
    )
    return f"skipped, not proven: {reason}"


def run_one(claim: Claim, cwd: Path, timeout: int = DEFAULT_TIMEOUT) -> ClaimResult:
    """Run one claim's check. A timeout is a failure, not a pass."""
    argv = shlex.split(claim.check)
    if not argv:
        return ClaimResult(claim, False, "empty check")
    # A claim owns its own temp root, its own basetemp and no shared pytest cache,
    # so two claims running at once cannot collide. None of it changes what the
    # command checks.
    env = dict(os.environ)
    env["PYTEST_ADDOPTS"] = (env.get("PYTEST_ADDOPTS", "") + " -p no:cacheprovider").strip()
    try:
        with tempfile.TemporaryDirectory(prefix="council-claim-") as tmp:
            env["TMPDIR"] = tmp
            proc = subprocess.run(_with_basetemp(argv, Path(tmp)), cwd=cwd,
                                  capture_output=True, text=True,
                                  timeout=timeout, env=env)
    except FileNotFoundError:
        return ClaimResult(claim, False, f"check command not found: {argv[0]}")
    except subprocess.TimeoutExpired:
        return ClaimResult(claim, False, f"check timed out after {timeout}s")

    ok = proc.returncode == 0
    if ok:
        unproven = _unproven(argv, proc.stdout or "")
        if unproven is not None:
            return ClaimResult(claim, False, unproven)
        return ClaimResult(claim, True, "")
    tail = (proc.stderr or proc.stdout).strip().splitlines()
    return ClaimResult(claim, False, f"exit {proc.returncode}: {tail[-1] if tail else ''}".rstrip())


def run_all(claims: list[Claim],
            cwd: Path,
            timeout: int = DEFAULT_TIMEOUT,
            jobs: int = 0) -> list[ClaimResult]:
    """Run every claim and keep going after a failure; report in registry order.

    Each check is an independent process, so the pool decides only when a claim
    runs. Two hundred and sixty-three claims at roughly a second of interpreter
    startup each is the entire cost of this check; it is not the work.
    """
    if jobs <= 1 or len(claims) <= 1:
        return [run_one(claim, cwd, timeout) for claim in claims]
    with ThreadPoolExecutor(max_workers=jobs) as pool:
        # `map` preserves input order, so the report is registry order either way.
        return list(pool.map(lambda c: run_one(c, cwd, timeout), claims))


def main(argv: list[str] | None = None) -> int:
    """`council-verify [--registry PATH] [--list] [--write PATH] [--check PATH]`."""
    parser = argparse.ArgumentParser(prog="council-verify",
                                     description="Run every claim in the registry.")
    parser.add_argument("--registry", type=Path, default=DEFAULT_REGISTRY)
    parser.add_argument("--list", action="store_true", help="list the claims")
    parser.add_argument("--write", type=Path, default=None, help="write the registry as markdown")
    parser.add_argument("--check", type=Path, default=None,
                        help="fail if the given markdown is not what the registry renders")
    parser.add_argument("--jobs", type=int, default=0,
                        help="claims to run at once (0 = one per core)")
    try:
        args = parser.parse_args(sys.argv[1:] if argv is None else argv)
    except SystemExit as exc:
        # 2 is reserved for an incomplete review; a usage error is a start failure.
        raise SystemExit(exc.code if exc.code == 0 else 3) from exc

    try:
        claims = load(args.registry)
    except RegistryError as exc:
        print(f"claims: {exc}", file=sys.stderr)
        return 3

    if args.list:
        for claim in claims:
            print(f"{claim.id}\t{claim.text}")
        return 0

    if args.write is not None:
        args.write.parent.mkdir(parents=True, exist_ok=True)
        args.write.write_text(render(claims), encoding="utf-8", newline="\n")
        print(f"wrote {args.write} ({len(claims)} claims)")
        return 0

    if args.check is not None:
        current = args.check.read_text(encoding="utf-8") if args.check.exists() else ""
        if current != render(claims):
            print(f"{args.check} does not match the registry: "
                  f"run `council-verify --write {args.check}`", file=sys.stderr)
            return 1
        print(f"{args.check} matches the registry ({len(claims)} claims)")
        return 0

    jobs = args.jobs or (os.cpu_count() or 1)
    results = run_all(claims, Path.cwd(), jobs=jobs)
    failed = [r for r in results if not r.ok]
    for result in results:
        mark = "ok  " if result.ok else "FAIL"
        print(f"  {mark} {result.claim.id}: {result.claim.text}")
        if not result.ok:
            print(f"       {result.detail}")
    print(f"\n{len(results) - len(failed)}/{len(results)} claims hold")
    return 0 if not failed else 1


if __name__ == "__main__":
    raise SystemExit(main())
